const tabLinks = document.querySelectorAll('.main-nav a[data-tab]');
const tabPanels = document.querySelectorAll('[data-panel-groups]');

const hashToTab = {
  '#about': 'about',
  '#to-c-service': 'serviceC',
  '#marketplace': 'serviceC',
  '#to-b-service': 'serviceB',
  '#b2b-sessions': 'serviceB',
  '#enterprise-promo': 'serviceB',
  '#oem-partnership': 'oem',
  '#contact': 'contact'
};

function panelBelongsToTab(panel, tab) {
  const groups = (panel.getAttribute('data-panel-groups') || '').split(/\s+/).filter(Boolean);
  return groups.includes(tab);
}

function setActiveTab(tab, updateHash = true) {
  if (!tab) {
    return;
  }

  tabLinks.forEach((link) => {
    const isActive = link.dataset.tab === tab;
    link.classList.toggle('is-active', isActive);
    if (isActive) {
      link.setAttribute('aria-current', 'page');
    } else {
      link.removeAttribute('aria-current');
    }
  });

  tabPanels.forEach((panel) => {
    panel.hidden = !panelBelongsToTab(panel, tab);
  });

  if (updateHash) {
    const activeLink = document.querySelector(`.main-nav a[data-tab="${tab}"]`);
    if (activeLink && activeLink.getAttribute('href')) {
      history.replaceState(null, '', activeLink.getAttribute('href'));
    }
  }
}

tabLinks.forEach((link) => {
  link.addEventListener('click', (event) => {
    event.preventDefault();
    setActiveTab(link.dataset.tab);
  });
});

window.addEventListener('hashchange', () => {
  const activeTab = hashToTab[window.location.hash] || 'about';
  setActiveTab(activeTab, false);
});

const initialTab = hashToTab[window.location.hash] || 'about';
setActiveTab(initialTab, false);
