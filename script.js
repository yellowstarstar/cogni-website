const translatableNodes = document.querySelectorAll('[data-i18n]');
const langSwitch = document.querySelector('#lang-switch');
const contactCtaLink = document.querySelector('a[data-i18n="contact.cta"]');
const b2bPlatformLink = document.querySelector('a[data-i18n="audience.b2b.link"]');
const enterpriseServiceLink = document.querySelector('a[data-i18n="promo.ctaSecondary"]');

const localeDomainConfig = {
  'zh-TW': {
    mailDomain: 'cogniplatforms.com.hk',
    webDomain: 'cogniplatforms.com.hk'
  },
  'zh-CN': {
    mailDomain: 'cogniplatforms.com.cn',
    webDomain: 'cogniplatforms.com.cn'
  },
  default: {
    mailDomain: 'cogniplatforms.com',
    webDomain: 'cogniplatforms.com'
  }
};

function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  const domainConfig = localeDomainConfig[lang] || localeDomainConfig.default;
  translatableNodes.forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (!(key in dictionary)) {
      return;
    }
    if (key.startsWith('domains.item') || key === 'contact.body') {
      node.innerHTML = dictionary[key];
      return;
    }
    node.textContent = dictionary[key];
  });

  document.documentElement.lang = lang;
  localStorage.setItem('preferredLang', lang);

  if (contactCtaLink) {
    contactCtaLink.href = `mailto:sales@${domainConfig.mailDomain}`;
  }

  if (b2bPlatformLink) {
    b2bPlatformLink.href = `https://${domainConfig.webDomain}`;
  }

  if (enterpriseServiceLink) {
    enterpriseServiceLink.href = `https://${domainConfig.webDomain}`;
  }
}


// 根據 domain 自動切換預設語言
function detectDefaultLang() {
  const host = window.location.hostname;
  if (host.endsWith('.com.hk')) return 'zh-TW';
  if (host.endsWith('.com.cn')) return 'zh-CN';
  if (host.endsWith('.com')) return 'en';
  return 'en';
}

const preferred = localStorage.getItem('preferredLang') || detectDefaultLang();
langSwitch.value = preferred;
applyLanguage(preferred);

langSwitch.addEventListener('change', (event) => {
  applyLanguage(event.target.value);
});

